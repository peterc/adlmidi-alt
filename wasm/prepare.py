#!/usr/bin/env python3
"""Extract a browser-only engine from the frozen sources in vendor/."""
from pathlib import Path
import argparse, hashlib, re, json, subprocess
root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--refresh-vendor', action='store_true',
                    help='copy the current parent checkout engine into vendor/ before building')
args = parser.parse_args()
if args.refresh_vendor:
    sources = {name: 'src/' + name for name in
               ['midiplay.cc', 'dbopl.cpp', 'dbopl.h', 'adldata.cc', 'adldata.hh', 'fraction']}
    sources['UPSTREAM-README.md'] = 'README.md'
    # Read everything first so a missing source cannot leave a partial snapshot.
    contents = {name: (root.parent / path).read_bytes() for name, path in sources.items()}
    revision = subprocess.run(['git', '-C', str(root.parent), 'rev-parse', 'HEAD'],
                              capture_output=True, text=True, check=True).stdout.strip()
    for name, data in contents.items():
        (root / 'vendor' / name).write_bytes(data)
    (root / 'vendor/source.json').write_text(json.dumps({
        'checkoutCommit': revision,
        'files': {name: {'source': sources[name], 'sha256': hashlib.sha256(data).hexdigest()}
                  for name, data in contents.items()}
    }, indent=2) + '\n')
original = (root / 'vendor/midiplay.cc').read_text()
def section(start, end):
    return original[original.index(start):original.index(end)]
header = '''// Generated by prepare.py from the vendored ADLMIDI fork. GPL-3.0.
#include <vector>
#include <string>
#include <string_view>
#include <map>
#include <set>
#include <deque>
#include <array>
#include <memory>
#include <algorithm>
#include <cstdlib>
#include <cstring>
#include <cstdint>
#include <cmath>
#include <cstdio>
#include <cassert>
#include <cerrno>
#include <stdexcept>
#include <limits>
#include "dbopl.h"
#include "adldata.hh"
#include "fraction"
static unsigned long PCM_RATE = 48000;
static constexpr unsigned MaxSamplesAtTime = 512;
static unsigned AdlBank=1, NumCards=4, NumFourOps=16;
static bool HighTremoloMode=false, HighVibratoMode=false, AdlPercussionMode=false;
static bool LogarithmicVolumes=false, CartoonersVolumes=false, ScaleModulators=false;
static bool BrowserLoop=true;
static bool WritingToTTY=false, QuitFlag=false, QuitWithoutLooping=false, FolderPlayback=true;
static constexpr int TrackChange=0;
// A fixed-size state snapshot replaces terminal rendering.
static int32_t VisualNotes[16*23*4] = {};
static int32_t ChannelPrograms[16] = {};
struct BrowserUI {
    template<class... T> void PrintLn(const char*, T...) {}
    void SetChannel(unsigned channel, unsigned patch, const std::string&) {
        // Fold virtual MIDI devices into the same 16 rows as the level meters.
        // If devices share a row, show the most recently reported program.
        ChannelPrograms[channel%16]=patch;
    }
    void IllustrateNote(unsigned voice, int note, unsigned ins, int pressure, double, unsigned channel) {
        if(voice>=16*23) return;
        int32_t* state=VisualNotes+voice*4;
        state[0]=channel; state[1]=note; state[2]=ins;
        state[3]=pressure<0 ? 40 : pressure;
    }
} UI;
'''
core = section('struct OPL3\n', '\n#ifndef __DJGPP__\nstruct Reverb')
core = core.replace('fraction<long>', 'fraction<int64_t>')
core = core.replace('1000000l * DeltaTicks', 'INT64_C(1000000) * DeltaTicks')
core = core.replace('(long) ReadBEint', '(int64_t) ReadBEint')
core = core.replace('shortest * Tempo', 'int64_t(shortest) * Tempo')
core = core.replace('"NRPN"+!nrpn', '&"NRPN"[!nrpn]')
core = core.replace('bool loopStart, loopEnd;', 'bool loopStart=false, loopEnd=false;')
# The engine now owns release tails, default tempo, and bounded event processing.
# End-of-file repeats happen in the worklet after the tail; markers loop in C++.
# Fail loudly if an upstream change invalidates these browser-specific patches.
def replace_once(text, old, new):
    if text.count(old) != 1:
        raise RuntimeError('Engine changed; review browser adaptation: ' + old)
    return text.replace(old, new)
core = replace_once(core, '(loopEnd && !FolderPlayback)', '(loopEnd && BrowserLoop)')
core = replace_once(core, 'if(FolderPlayback || QuitWithoutLooping || loop_elapsed <= 0)',
                    'if(shortest < 0 || !BrowserLoop || loop_elapsed <= 0)')
# Track the displayed time signature, including marker-loop restores.
core = replace_once(core, 'fraction<int64_t> InvDeltaTicks, Tempo;',
                    'fraction<int64_t> InvDeltaTicks, Tempo;\n    unsigned BrowserSignature=0, LoopBeginSignature=0;')
core = replace_once(core, 'LoopBeginTempo = Tempo;',
                    'LoopBeginTempo = Tempo;\n            LoopBeginSignature = BrowserSignature;')
core = replace_once(core, 'Tempo = LoopBeginTempo;',
                    'Tempo = LoopBeginTempo;\n            BrowserSignature = LoopBeginSignature;')
core = replace_once(core, '            if(evtype == 0x51)', '''            if(evtype == 0x58 && data.size() == 4
                && (unsigned char)data[0] > 0 && (unsigned char)data[1] <= 7)
                BrowserSignature = ((unsigned char)data[0] << 8) | (unsigned char)data[1];
            if(evtype == 0x51)''')
reverb = section('struct Reverb /*', '\nstatic bool ParseNumber')
(root/'src/core.inc').write_text(header + section('static const unsigned short Operators', '\nclass Input\n') + core + reverb)
# Remove SDL's typedef-only dependency in the browser copy.
adlh = (root/'vendor/adldata.hh').read_text()
adlh = adlh[adlh.index('extern const struct adldata'):]
(root/'src/adldata.hh').write_text('#pragma once\n#include <cstdint>\nusing Uint8=uint8_t; using Uint16=uint16_t; using Uint32=uint32_t;\n'+adlh)
for name in ['dbopl.cpp','dbopl.h','adldata.cc','fraction']:
    (root/'src'/name).write_bytes((root/'vendor'/name).read_bytes())
# Observe voice sample peaks without changing the synthesized samples. Keep the
# vendor snapshot untouched so this small browser-only hook survives rebuilds.
oplh = (root/'src/dbopl.h').read_text()
oplh = replace_once(oplh, 'struct Channel {', 'struct Channel {\n\tBit32s meterPeak = 0;')
(root/'src/dbopl.h').write_text(oplh)
oplc = (root/'src/dbopl.cpp').read_text()
oplc = replace_once(oplc, '\t\tswitch( mode ) {\n\t\tcase sm2AM:',
'''        // Pre-effect voice peak for the browser's MIDI channel meters.
        const Bit32s amplitude = sample < 0 ? -sample : sample;
        if (amplitude > meterPeak) meterPeak = amplitude;
\t\tswitch( mode ) {\n\t\tcase sm2AM:''')
(root/'src/dbopl.cpp').write_text(oplc)
banks = section('static const char* const GMNames', 'static const char PercussionMap')
names = re.findall(r'"([^"\\]*)"', banks)
(root/'assets/programs.json').write_text(json.dumps(names)+'\n')

adldata = (root/'vendor/adldata.cc').read_text()
bankblock = adldata[adldata.index('const char* const banknames'):adldata.index('const unsigned short banks')]
(root/'assets/banks.json').write_text(json.dumps(re.findall(r'"([^"\\]*)"', bankblock))+'\n')

# Optional local demos are not required for a checkout to build and play.
demos = [name for name in ('so-pastdays.mid', 'so-town2.mid', 'wiz5-artifacts.mid')
         if (root/'assets'/name).is_file()]
(root/'assets/demo-playlist.json').write_text(json.dumps(demos or ['copper-circuit.mid'])+'\n')
